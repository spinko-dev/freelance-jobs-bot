def parse_source_chats(raw: str) -> list[str | int]:
    """>@username или числовые ID через запятую."""
    result: list[str | int] = []
    for part in raw.split(","):
        part = part.strip().lstrip("@")
        if not part:
            continue
        result.append(int(part) if part.lstrip("-").isdigit() else part)
    return result


